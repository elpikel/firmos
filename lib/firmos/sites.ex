defmodule Firmos.Sites do
  @moduledoc """
  Companies' landing pages.

  Each company has at most one `Firmos.Sites.Site`. Its content lives in
  immutable, numbered `Firmos.Sites.Version`s: every content change inserts
  version n+1 and moves the site's `current_version` pointer, so older
  versions are kept (STORY-010 undo moves the pointer back).

  A version is generated by the AI in the background by
  `Firmos.Sites.GenerateWorker` (Oban, queue `ai`), from the company and its
  ready business plan. `request_generation/2` inserts the job in the same
  transaction that queues the site, so a job never exists for a rolled-back
  request. The AI returns structured text only (`Firmos.Sites.Content`); the
  page is rendered, escaped, by `FirmosWeb.SiteComponents.landing/1`.

  Owner-facing functions take the caller's `Firmos.Accounts.Scope` and only
  ever see that owner's sites. `generate_site/3` and `mark_failed/3` are the
  worker's entry points and take bare ids: the site's and the Oban job's.
  The job id is the generation's claim token: only the job that claimed a
  generation can store its result or fail it, so a stale job that wakes up
  after the owner asked again can't overwrite the newer generation.

  The owner edits the current version's text (`update_content/3`: a new
  `edited` version), chooses the site's slug (`set_slug/3`) and publishes
  (`publish/2`): the site's `published_version` is what customers see at
  `<slug>.<base domain>`, read through the one unscoped, public function
  `get_published_by_slug/1`. Later edits stay a draft until the owner
  publishes again.

  The owner can undo the latest site change from the activity log
  (`undoable_entry_id/2`, `undo/3`): the previous version's content comes
  back as a new `undo` version, live again if the undone change was live.

  Every change to a site (generation status, content, slug, publication) is
  broadcast on the company's site topic (see `subscribe/2`) after it commits.
  """
  import Ecto.Query, warn: false

  alias Firmos.Accounts.Scope
  alias Firmos.Activity
  alias Firmos.Activity.Entry
  alias Firmos.AI
  alias Firmos.AI.ErrorCode
  alias Firmos.Companies.Company
  alias Firmos.Plans
  alias Firmos.Repo
  alias Firmos.Sites.Content
  alias Firmos.Sites.GenerateWorker
  alias Firmos.Sites.Prompt
  alias Firmos.Sites.Site
  alias Firmos.Sites.Version

  @in_progress [:pending, :generating]

  # Same reasoning as Firmos.Plans: longer than the worst-case AI call plus
  # Lifeline's `rescue_after` and a resumed second attempt.
  @stale_after_minutes 120

  @typedoc """
  The message `subscribe/2` delivers after a site changes (re-read the site
  for anything beyond these fields).
  """
  @type update_message ::
          {:site_updated,
           %{
             id: integer(),
             company_id: integer(),
             generation_status: Site.generation_status(),
             current_version_id: integer() | nil
           }}

  @doc """
  Subscribes the caller to updates of the company's site: a
  `t:update_message/0` after every generation status change. Raises
  `FunctionClauseError` for a company the scope doesn't own.
  """
  @spec subscribe(%Scope{}, Company.t()) :: :ok | {:error, term()}
  def subscribe(%Scope{user: %{id: user_id}}, %Company{id: company_id, user_id: user_id}) do
    Phoenix.PubSub.subscribe(Firmos.PubSub, topic(company_id))
  end

  @doc """
  Stops the caller's `subscribe/2` updates for the company's site (e.g. when
  a page switches to another company). Raises `FunctionClauseError` for a
  company the scope doesn't own.
  """
  @spec unsubscribe(%Scope{}, Company.t()) :: :ok
  def unsubscribe(%Scope{user: %{id: user_id}}, %Company{id: company_id, user_id: user_id}) do
    Phoenix.PubSub.unsubscribe(Firmos.PubSub, topic(company_id))
  end

  @doc """
  The company's site with its current version preloaded, or `nil` when the
  owner never asked for one.
  """
  @spec get_site(%Scope{}, Company.t()) :: Site.t() | nil
  def get_site(%Scope{user: %{id: user_id}}, %Company{id: company_id}) do
    from(s in Site, as: :site)
    |> join(:inner, [site: s], c in assoc(s, :company), as: :company)
    |> where([site: s], s.company_id == ^company_id)
    |> where([company: c], c.user_id == ^user_id)
    |> join(:left, [site: s], v in assoc(s, :current_version), as: :current_version)
    |> preload([current_version: v], current_version: v)
    |> Repo.one()
  end

  @doc """
  A changeset of the site's current content with the owner's `attrs`
  applied, for the editor form (see `Firmos.Sites.Content.edit_changeset/2`).
  """
  @spec change_content(Site.t(), map()) :: Ecto.Changeset.t()
  def change_content(%Site{current_version: %Version{content: content}}, attrs \\ %{}) do
    Content.edit_changeset(content, attrs)
  end

  @doc """
  Saves the owner's edit of the site's content.

  Under the site's row lock, applies `attrs` to the CURRENT version's
  content and, when a field changed, in one transaction inserts version n+1
  (source `edited`), makes it the current version and records
  `site_updated` (subject the version, metadata the version number and the
  changed `"section.field"` paths). Nothing changed → the site is returned
  as it is: no version, no entry. The published version is untouched until
  `publish/2`.

  The edit is based on `site`'s `current_version_id` as the caller loaded
  it (the editor's copy, held server-side since it opened): when the site
  has moved to another version since (another tab saved, an undo, a new
  generation), the edit is refused with `:stale` instead of overwriting
  that change.

  Refused while a generation is in progress (`:generation_in_progress`),
  without content (`:no_content`), for another owner's site (`:not_found`),
  when stale (`:stale`), and with the content changeset when the edit is
  invalid.
  """
  @spec update_content(%Scope{}, Site.t(), map()) ::
          {:ok, Site.t()}
          | {:error,
             :not_found
             | :no_content
             | :generation_in_progress
             | :stale
             | Ecto.Changeset.t()}
  def update_content(%Scope{} = scope, %Site{id: site_id, current_version_id: base_id}, attrs)
      when is_map(attrs) do
    Repo.transact(fn ->
      with {:ok, site} <- lock_site(scope, site_id),
           :ok <- ensure_not_in_progress(site),
           {:ok, current} <- current_version(site),
           :ok <- ensure_based_on(current, base_id),
           {:ok, content} <-
             current.content
             |> Content.edit_changeset(attrs)
             |> Ecto.Changeset.apply_action(:update) do
        case Content.changed_paths(current.content, content) do
          [] -> {:ok, site}
          fields -> store_edit(scope, site, content, fields)
        end
      end
    end)
    |> broadcast_ok()
  end

  defp store_edit(scope, site, content, fields) do
    with {:ok, {updated_site, version}} <- insert_version(site, content, :edited),
         {:ok, _entry} <-
           Activity.record(site.company, scope, :site_updated,
             subject: {"site_version", version.id},
             metadata: %{"version" => version.number, "fields" => fields}
           ) do
      {:ok, %{updated_site | current_version: version}}
    end
  end

  defp ensure_based_on(%Version{id: base_id}, base_id), do: :ok
  defp ensure_based_on(%Version{}, _moved), do: {:error, :stale}

  @doc """
  The company's activity entry the owner can undo right now, or `nil`.

  Only the company's latest site-changing entry (`site_generated`,
  `site_updated`, `site_published` or `site_undone`) can be undone, and
  only when it is not itself an undo (no redo), it is about the site's
  current version, there is a version to go back to, and no generation is
  in progress. The version to go back to is the one before the entry's
  version for a generation or an edit, and the version that was published
  before for a publication (so the first publication can't be undone).
  `undo/3` re-checks the same rule under the site's lock.
  """
  @spec undoable_entry(%Scope{}, Company.t()) :: Entry.t() | nil
  def undoable_entry(%Scope{} = scope, %Company{} = company) do
    with %Site{} = site <- get_site(scope, company),
         {:ok, entry, _target} <- undoable(scope, %{site | company: company}) do
      entry
    else
      _nothing_to_undo -> nil
    end
  end

  @doc """
  Undoes the company's site change recorded by activity entry `entry_id`.

  Under the site's row lock and in one transaction: re-checks that the
  entry is still the undoable one (see `undoable_entry/2`), inserts
  version n+1 (source `undo`) with the content of the version to go back
  to, makes it the current version and, when the undone
  change was live (the published version was the current one), the
  published version too; records `site_undone` (subject the new version,
  metadata `version`, `restored_from_version`, `reverts_entry_id`,
  `reverts_entry_at`), then broadcasts.

  Refused for a company or entry the scope doesn't own (`:not_found`),
  while a generation is in progress (`:generation_in_progress`) and when
  the entry is not (or no longer) undoable (`:not_undoable`: an older
  change, an undo, or a second click).
  """
  @spec undo(%Scope{}, Company.t(), integer()) ::
          {:ok, Site.t()}
          | {:error, :not_found | :generation_in_progress | :not_undoable | Ecto.Changeset.t()}
  def undo(%Scope{} = scope, %Company{id: company_id}, entry_id) when is_integer(entry_id) do
    Repo.transact(fn ->
      with {:ok, site} <- lock_company_site(scope, company_id),
           {:ok, entry} <- Activity.fetch_entry(scope, site.company, entry_id),
           {:ok, %Entry{id: ^entry_id}, target} <- undoable(scope, site) do
        store_undo(scope, site, entry, target)
      else
        {:ok, _other_entry, _target} -> {:error, :not_undoable}
        error -> error
      end
    end)
    |> broadcast_ok()
  end

  @site_changes [:site_generated, :site_updated, :site_published, :site_undone]
  @undoable_changes [:site_generated, :site_updated, :site_published]

  # The one undo rule, shared by undoable_entry/2 and undo/3. `site` has
  # its company and current version loaded.
  defp undoable(scope, %Site{current_version: %Version{id: current_id} = current} = site) do
    with %Entry{action: action} = entry when action in @undoable_changes <-
           Activity.latest_for_company(scope, site.company, @site_changes),
         ^current_id <- Activity.subject_id(entry, "site_version"),
         :ok <- ensure_not_in_progress(site),
         %Version{} = target <- undo_target(scope, site, current, entry) do
      {:ok, entry, target}
    else
      {:error, :generation_in_progress} = error -> error
      _nothing_to_undo -> {:error, :not_undoable}
    end
  end

  defp undoable(_scope, %Site{}), do: {:error, :not_undoable}

  # Undoing a publication puts back what was published before it (never a
  # draft that was rejected in between); the first publication has nothing
  # to go back to.
  defp undo_target(scope, site, _current, %Entry{action: :site_published} = entry) do
    case previously_published_id(scope, site, entry) do
      nil -> nil
      version_id -> Repo.get_by(Version, id: version_id, site_id: site.id)
    end
  end

  # Every generation, edit and undo moves the current version from the one
  # numbered just before it.
  defp undo_target(_scope, site, current, _change_entry) do
    from(v in Version, as: :version)
    |> where([version: v], v.site_id == ^site.id and v.number < ^current.number)
    |> order_by([version: v], desc: v.number)
    |> limit(1)
    |> Repo.one()
  end

  defp previously_published_id(_scope, _site, %Entry{
         metadata: %{"previous_published_version_id" => version_id}
       }),
       do: version_id

  # Entries recorded before the metadata existed: the previous publication.
  defp previously_published_id(scope, site, entry) do
    case Activity.latest_for_company(scope, site.company, [:site_published],
           before: Activity.cursor(entry)
         ) do
      nil -> nil
      previous -> Activity.subject_id(previous, "site_version")
    end
  end

  defp store_undo(scope, site, entry, target) do
    live? = site.published_version_id == site.current_version_id

    with {:ok, {updated_site, version}} <- insert_version(site, target.content, :undo),
         {:ok, updated_site} <- republish_if(live?, updated_site),
         {:ok, _entry} <-
           Activity.record(site.company, scope, :site_undone,
             subject: {"site_version", version.id},
             metadata: %{
               "version" => version.number,
               "restored_from_version" => target.number,
               "reverts_entry_id" => entry.id,
               "reverts_entry_at" => DateTime.to_iso8601(entry.inserted_at)
             }
           ) do
      {:ok, %{updated_site | current_version: version}}
    end
  end

  # Undoing a live change makes the restored content live; undoing a
  # draft-only edit must not publish the older draft.
  defp republish_if(true, site), do: site |> Site.publish_changeset() |> Repo.update()
  defp republish_if(false, site), do: {:ok, site}

  @doc "A changeset of the site's slug for the slug form."
  @spec change_slug(Site.t(), map()) :: Ecto.Changeset.t()
  def change_slug(%Site{} = site, attrs \\ %{}), do: Site.slug_changeset(site, attrs)

  @doc """
  Sets the site's slug, the label of its public address. The input is
  trimmed and downcased; an invalid, reserved or taken slug (in any letter
  case) is `{:error, changeset}`. Changing the slug of a published site
  moves it to the new address at once: the old one answers 404.
  """
  @spec set_slug(%Scope{}, Site.t(), String.t()) ::
          {:ok, Site.t()} | {:error, :not_found | Ecto.Changeset.t()}
  def set_slug(%Scope{} = scope, %Site{id: site_id}, slug) when is_binary(slug) do
    Repo.transact(fn ->
      with {:ok, site} <- lock_site(scope, site_id) do
        site |> Site.slug_changeset(%{"slug" => slug}) |> Repo.update()
      end
    end)
    |> broadcast_ok()
  end

  @doc """
  Publishes the site's current version at its slug's address.

  Under the site's row lock and in one transaction: the current version
  becomes the published one, the site `published`, and `site_published` is
  recorded (subject the version, metadata the slug, the version number and
  the `previous_published_version_id`, `nil` on the first publication, which
  `undo/3` puts back live).
  Publishing the version that is already published changes nothing.

  Refused without a current version (`:no_content`), without a slug
  (`:slug_required`) and for another owner's site (`:not_found`).
  """
  @spec publish(%Scope{}, Site.t()) ::
          {:ok, Site.t()}
          | {:error, :not_found | :no_content | :slug_required | Ecto.Changeset.t()}
  def publish(%Scope{} = scope, %Site{id: site_id}) do
    Repo.transact(fn ->
      with {:ok, site} <- lock_site(scope, site_id),
           {:ok, version} <- current_version(site),
           :ok <- ensure_slug(site) do
        if published?(site) and site.published_version_id == version.id do
          {:ok, site}
        else
          store_publication(scope, site, version)
        end
      end
    end)
    |> broadcast_ok()
  end

  defp store_publication(scope, site, version) do
    with {:ok, published} <- site |> Site.publish_changeset() |> Repo.update(),
         {:ok, _entry} <-
           Activity.record(site.company, scope, :site_published,
             subject: {"site_version", version.id},
             metadata: %{
               "slug" => published.slug,
               "version" => version.number,
               "previous_published_version_id" => site.published_version_id
             }
           ) do
      {:ok, published}
    end
  end

  @doc "Whether customers can see the site."
  @spec published?(Site.t() | nil) :: boolean()
  def published?(%Site{status: :published}), do: true
  def published?(_draft_or_nil), do: false

  @doc "Whether the draft differs from what is published (always false before publishing)."
  @spec unpublished_changes?(Site.t() | nil) :: boolean()
  def unpublished_changes?(%Site{} = site),
    do: published?(site) and site.current_version_id != site.published_version_id

  def unpublished_changes?(nil), do: false

  @doc """
  The published site at `slug` with its published version and company
  preloaded, for the public page. Unscoped: anyone may read a published
  site. A site that was never published is `{:error, :not_found}`, like an
  unknown slug.
  """
  @spec get_published_by_slug(String.t()) :: {:ok, Site.t()} | {:error, :not_found}
  def get_published_by_slug(slug) when is_binary(slug) do
    from(s in Site, as: :site)
    |> where([site: s], s.slug == ^slug and s.status == :published)
    |> where([site: s], not is_nil(s.published_version_id))
    |> preload([:company, :published_version])
    |> Repo.one()
    |> case do
      nil -> {:error, :not_found}
      site -> {:ok, site}
    end
  end

  @doc """
  Queues the AI generation of a new site version (the owner's "create
  website", "regenerate" and "try again"): creates the company's site if it
  has none, sets it `pending` and enqueues the job, in one transaction.
  Existing versions are kept.

  Refused when the company's current plan is not ready
  (`:no_ready_plan`) and while a generation is pending or running
  (`:generation_in_progress`), unless it has `stalled?/1`. The company row
  is locked, so a double click can't queue two generations. Raises
  `FunctionClauseError` for a company the scope doesn't own.
  """
  @spec request_generation(%Scope{}, Company.t()) ::
          {:ok, Site.t()}
          | {:error, :not_found | :no_ready_plan | :generation_in_progress | Ecto.Changeset.t()}
  def request_generation(
        %Scope{user: %{id: user_id}} = scope,
        %Company{id: company_id, user_id: user_id}
      ) do
    Repo.transact(fn ->
      with {:ok, company} <- lock_company(scope, company_id),
           {:ok, _plan} <- Plans.ready_plan(scope, company),
           {:ok, site} <- get_or_create_site(company),
           :ok <- ensure_not_in_progress(site),
           {:ok, pending} <- site |> Site.pending_changeset() |> Repo.update(),
           {:ok, _job} <- enqueue(pending) do
        {:ok, pending}
      end
    end)
    |> broadcast_ok()
  end

  @doc """
  Whether a pending or generating site has stalled: its job died without
  storing a result (#{@stale_after_minutes} minutes without a change). A
  stalled generation can be requested again like a failed one.
  """
  @spec stalled?(Site.t()) :: boolean()
  def stalled?(%Site{generation_status: status, updated_at: %DateTime{} = updated_at})
      when status in @in_progress do
    DateTime.diff(DateTime.utc_now(), updated_at, :minute) >= @stale_after_minutes
  end

  def stalled?(%Site{}), do: false

  @doc "Whether a generation is queued or running (and hasn't stalled)."
  @spec generation_in_progress?(Site.t() | nil) :: boolean()
  def generation_in_progress?(%Site{generation_status: status} = site),
    do: status in @in_progress and not stalled?(site)

  def generation_in_progress?(nil), do: false

  @doc "Whether the last generation failed or stalled, so the owner should try again."
  @spec generation_failed?(Site.t() | nil) :: boolean()
  def generation_failed?(%Site{generation_status: :failed}), do: true
  def generation_failed?(%Site{} = site), do: stalled?(site)
  def generation_failed?(nil), do: false

  @doc """
  Generates the next version of site `site_id` in Oban job `job_id` (the
  worker's entry point).

  Claims the site for `job_id` by moving it from `pending` to `generating`
  (`resume: true` also takes the site back when it is still `generating` for
  this same job, resumed after a crash), asks the
  AI for the content from the company and its current ready plan, and
  stores the result:

    * `{:ok, version}` - in one transaction: version n+1 (source
      `generated`) is inserted, becomes the site's current version, the
      generation goes back to `idle`, and a `site_generated` entry by the
      agent is recorded
    * `{:error, {:generation_failed, code}}` - no ready plan, the AI call
      failed or its reply was not valid content; the site is stored
      `failed` with the safe `code` and no version is inserted
    * `{:error, :not_claimable}` - nothing to do (unknown id, not pending,
      or another job has it), or the claim was lost while the AI was
      working (the owner asked again); nothing is stored

  The contact email and city come from the company profile, never from the
  AI. Blocks for as long as the AI call takes; run it only from the job.
  """
  @spec generate_site(integer(), integer(), resume: boolean()) ::
          {:ok, Version.t()}
          | {:error, :not_claimable | {:generation_failed, String.t()} | Ecto.Changeset.t()}
  def generate_site(site_id, job_id, opts \\ [])
      when is_integer(site_id) and is_integer(job_id) do
    with {:ok, site} <- claim(site_id, job_id, Keyword.get(opts, :resume, false)) do
      broadcast(site)

      case request_content(site.company) do
        {:ok, content} -> store_version(site, job_id, content)
        {:error, reason} -> store_failed(site, job_id, failure_code(reason))
      end
    end
  end

  @doc """
  Marks the generation of site `site_id` failed with the safe `code`, if it
  is still `generating` for Oban job `job_id` (the worker's last resort when
  a final attempt could not store its result). Unscoped, like
  `generate_site/3`.
  """
  @spec mark_failed(integer(), integer(), String.t()) :: {:ok, Site.t()} | {:error, :not_found}
  def mark_failed(site_id, job_id, code)
      when is_integer(site_id) and is_integer(job_id) and is_binary(code) do
    from(s in Site, as: :site, select: s)
    |> where([site: s], s.id == ^site_id)
    |> where_claimed_by(job_id)
    |> Repo.update_all(
      set: [generation_status: :failed, generation_error: code, updated_at: now()]
    )
    |> case do
      {1, [site]} ->
        broadcast(site)
        {:ok, site}

      {0, []} ->
        {:error, :not_found}
    end
  end

  defp claim(site_id, job_id, resume?) do
    from(s in Site, as: :site, select: s)
    |> where([site: s], s.id == ^site_id)
    |> where_claimable(job_id, resume?)
    |> Repo.update_all(
      set: [generation_status: :generating, generation_job_id: job_id, updated_at: now()]
    )
    |> case do
      {1, [site]} -> {:ok, Repo.preload(site, company: :user)}
      {0, []} -> {:error, :not_claimable}
    end
  end

  # The agent reads the plan as the owner would, through the owner's scope.
  defp request_content(%Company{user: user} = company) do
    with {:ok, plan} <- Plans.ready_plan(Scope.for_user(user), company),
         {:ok, text} <-
           company |> Prompt.for_company(plan.content) |> AI.complete(system: Prompt.system()) do
      Content.from_json(text, %{
        "email" => company.contact_email,
        "phone" => nil,
        "city" => company.city
      })
    end
  end

  defp failure_code(:no_ready_plan), do: "no_ready_plan"
  defp failure_code(reason), do: ErrorCode.from_reason(reason)

  defp where_claimable(query, _job_id, false),
    do: where(query, [site: s], s.generation_status == :pending)

  defp where_claimable(query, job_id, true) do
    where(
      query,
      [site: s],
      s.generation_status == :pending or
        (s.generation_status == :generating and s.generation_job_id == ^job_id)
    )
  end

  defp where_claimed_by(query, job_id) do
    where(
      query,
      [site: s],
      s.generation_status == :generating and s.generation_job_id == ^job_id
    )
  end

  defp store_version(%Site{id: site_id, company: company}, job_id, content) do
    Repo.transact(fn ->
      with {:ok, site} <- lock_claimed_site(site_id, job_id),
           {:ok, {updated_site, version}} <- insert_version(site, content, :generated),
           {:ok, _entry} <-
             Activity.record(company, :agent, :site_generated,
               subject: {"site_version", version.id},
               metadata: %{"version" => version.number}
             ) do
        {:ok, {updated_site, version}}
      end
    end)
    |> case do
      {:ok, {updated_site, version}} ->
        broadcast(updated_site)
        {:ok, version}

      error ->
        error
    end
  end

  # Locks the site only while job `job_id` still holds its generation claim.
  # A stalled job that wakes up after the owner asked again (the site is
  # pending again, or claimed by the newer job) finds nothing and stores
  # nothing, so the newer generation's result wins.
  defp lock_claimed_site(site_id, job_id) do
    from(s in Site, as: :site, lock: "FOR UPDATE")
    |> where([site: s], s.id == ^site_id)
    |> where_claimed_by(job_id)
    |> Repo.one()
    |> case do
      nil -> {:error, :not_claimable}
      site -> {:ok, site}
    end
  end

  # The one way content changes: insert version n+1 and point the site at
  # it. The caller holds the site's row lock, so numbering can't race.
  defp insert_version(site, content, source) do
    with {:ok, version} <-
           site.id
           |> Version.new_changeset(next_number(site.id), content, source)
           |> Repo.insert(),
         {:ok, updated_site} <- site |> pointer_changeset(version, source) |> Repo.update() do
      {:ok, {updated_site, version}}
    end
  end

  # A generated version also ends its generation; an owner's edit leaves
  # the generation status (e.g. a failed regeneration) as it is.
  defp pointer_changeset(site, version, :generated),
    do: Site.current_version_changeset(site, version)

  defp pointer_changeset(site, version, _owner),
    do: Site.current_version_pointer_changeset(site, version)

  defp next_number(site_id) do
    from(v in Version, as: :version)
    |> where([version: v], v.site_id == ^site_id)
    |> select([version: v], coalesce(max(v.number), 0) + 1)
    |> Repo.one!()
  end

  defp store_failed(%Site{id: site_id}, job_id, code) do
    Repo.transact(fn ->
      with {:ok, site} <- lock_claimed_site(site_id, job_id) do
        site |> Site.failed_changeset(code) |> Repo.update()
      end
    end)
    |> case do
      {:ok, failed} ->
        broadcast(failed)
        {:error, {:generation_failed, code}}

      error ->
        error
    end
  end

  defp get_or_create_site(%Company{id: company_id}) do
    case Repo.get_by(Site, company_id: company_id) do
      nil -> company_id |> Site.new_changeset() |> Repo.insert()
      site -> {:ok, site}
    end
  end

  defp enqueue(%Site{id: site_id}) do
    %{site_id: site_id}
    |> GenerateWorker.new()
    |> Oban.insert()
  end

  defp ensure_not_in_progress(site) do
    if generation_in_progress?(site), do: {:error, :generation_in_progress}, else: :ok
  end

  # The owner's site, locked, with its company and current version.
  defp lock_site(scope, site_id),
    do: lock_owned_site(scope, dynamic([site: s], s.id == ^site_id))

  defp lock_company_site(scope, company_id),
    do: lock_owned_site(scope, dynamic([site: s], s.company_id == ^company_id))

  defp lock_owned_site(%Scope{user: %{id: user_id}}, condition) do
    owned_company_ids =
      from(c in Company, as: :company, where: c.user_id == ^user_id, select: c.id)

    from(s in Site, as: :site, lock: "FOR UPDATE")
    |> where(^condition)
    |> where([site: s], s.company_id in subquery(owned_company_ids))
    |> Repo.one()
    |> case do
      nil -> {:error, :not_found}
      site -> {:ok, Repo.preload(site, [:company, :current_version])}
    end
  end

  defp current_version(%Site{current_version: %Version{} = version}), do: {:ok, version}
  defp current_version(%Site{}), do: {:error, :no_content}

  defp ensure_slug(%Site{slug: slug}) when is_binary(slug), do: :ok
  defp ensure_slug(%Site{}), do: {:error, :slug_required}

  defp lock_company(%Scope{user: %{id: user_id}}, company_id) do
    from(c in Company, as: :company, lock: "FOR UPDATE")
    |> where([company: c], c.id == ^company_id and c.user_id == ^user_id)
    |> Repo.one()
    |> case do
      nil -> {:error, :not_found}
      company -> {:ok, company}
    end
  end

  defp broadcast_ok({:ok, %Site{} = site} = result) do
    broadcast(site)
    result
  end

  defp broadcast_ok(error), do: error

  # The local PubSub adapter always answers :ok; anything else is a bug.
  defp broadcast(%Site{} = site) do
    :ok =
      Phoenix.PubSub.broadcast(
        Firmos.PubSub,
        topic(site.company_id),
        {:site_updated,
         %{
           id: site.id,
           company_id: site.company_id,
           generation_status: site.generation_status,
           current_version_id: site.current_version_id
         }}
      )
  end

  defp topic(company_id), do: "company:#{company_id}:site"

  defp now, do: DateTime.utc_now(:second)
end
