defmodule Firmos.Plans.Content do
  @moduledoc """
  The body of a business plan, as generated by the AI and stored in the
  `plans.content` jsonb column.

  `from_json/1` is the one way in: it decodes the AI's raw text and checks it
  has every section with the right type, so a plan is never stored half-formed.
  """
  use Ecto.Schema

  import Ecto.Changeset

  alias Firmos.Plans.Content.Task

  @text_fields [:offer, :target_customer, :pricing]
  @list_fields [:competitors, :channels]
  @max_text 4_000
  @max_list 20
  @max_list_item 300
  @max_tasks 40

  @type t :: %__MODULE__{
          offer: String.t() | nil,
          target_customer: String.t() | nil,
          competitors: [String.t()] | nil,
          pricing: String.t() | nil,
          channels: [String.t()] | nil,
          tasks_30_days: [Task.t()]
        }

  @primary_key false
  embedded_schema do
    field :offer, :string
    field :target_customer, :string
    # No `default: []`: a missing list must stay nil so validate_required sees it.
    field :competitors, {:array, :string}
    field :pricing, :string
    field :channels, {:array, :string}
    embeds_many :tasks_30_days, Task, on_replace: :delete
  end

  @doc """
  Decodes the AI's reply into validated content.

  Tolerates a Markdown code fence around the JSON (models add one despite
  the instructions). Returns `{:error, :invalid_json}` when the text is not a
  JSON object and `{:error, :invalid_shape}` when a section is missing,
  empty, too long or of the wrong type.
  """
  @spec from_json(String.t()) :: {:ok, t()} | {:error, :invalid_json | :invalid_shape}
  def from_json(text) when is_binary(text) do
    case text |> strip_code_fence() |> Jason.decode() do
      {:ok, %{} = attrs} -> validate(attrs)
      _not_an_object -> {:error, :invalid_json}
    end
  end

  defp validate(attrs) do
    %__MODULE__{}
    |> changeset(attrs)
    |> apply_action(:validate)
    |> case do
      {:ok, content} -> {:ok, content}
      {:error, _changeset} -> {:error, :invalid_shape}
    end
  end

  defp changeset(content, attrs) do
    content
    |> cast(attrs, @text_fields ++ @list_fields)
    |> cast_embed(:tasks_30_days, required: true, with: &Task.changeset/2)
    |> validate_required(@text_fields ++ @list_fields)
    |> validate_text_lengths()
    |> validate_lists()
    |> validate_length(:tasks_30_days, min: 1, max: @max_tasks)
  end

  defp validate_text_lengths(changeset) do
    Enum.reduce(@text_fields, changeset, &validate_length(&2, &1, max: @max_text))
  end

  defp validate_lists(changeset) do
    Enum.reduce(@list_fields, changeset, fn field, acc ->
      acc
      |> validate_length(field, min: 1, max: @max_list)
      |> validate_change(field, fn ^field, items ->
        if Enum.all?(items, &valid_list_item?/1), do: [], else: [{field, "has an invalid item"}]
      end)
    end)
  end

  defp valid_list_item?(item) when is_binary(item),
    do: String.trim(item) != "" and String.length(item) <= @max_list_item

  defp valid_list_item?(_null), do: false

  defp strip_code_fence(text) do
    text
    |> String.trim()
    |> String.replace(~r/\A```(?:json)?\s*(.*?)\s*```\z/s, "\\1")
  end
end
